"use server";

import { revalidatePath } from "next/cache";
import { createClient } from "@/lib/supabase/server";
import { hasAdminSession } from "@/app/lib/admin-session";
import { agentLanguages, normalizeAgentEmail, normalizeAgentPhone } from "@/app/lib/agent-verification";

export type AgentState = { result: "" | "saved" | "error" | "contact" | "duplicate"; code?: string };
const uuid = /^[\da-f]{8}-[\da-f]{4}-[\da-f]{4}-[\da-f]{4}-[\da-f]{12}$/i;
const plain = (value: string, min: number, max: number) => value.length >= min && value.length <= max && !/[\u0000-\u001f\u007f]/.test(value);

/** Creates or updates an agent: first and last name, official email and WhatsApp number are required;
 * the unique code is generated by the database and returned for display. */
export async function saveAgent(_previous: AgentState, form: FormData): Promise<AgentState> {
  try {
    const client = await createClient();
    const { data: { user }, error } = await client.auth.getUser();
    if (error || !(await hasAdminSession(client, user))) return { result: "error" };
    const id = String(form.get("id") || ""), firstName = String(form.get("first_name") || "").trim(), lastName = String(form.get("last_name") || "").trim();
    const title = String(form.get("title") || "").trim();
    const email = normalizeAgentEmail(String(form.get("email") || "")), whatsapp = normalizeAgentPhone(String(form.get("whatsapp") || ""));
    const languages = form.getAll("languages").map(String).filter((language): language is (typeof agentLanguages)[number] => (agentLanguages as readonly string[]).includes(language));
    if ((id && !uuid.test(id)) || !plain(firstName, 1, 59) || !plain(lastName, 1, 59) || (title && !plain(title, 2, 80))) return { result: "error" };
    if (!email || !whatsapp) return { result: "contact" };
    const { data, error: saveError } = await client.rpc("save_agent_profile", {
      p_id: id || null, p_first_name: firstName, p_last_name: lastName, p_email: email, p_whatsapp: whatsapp,
      p_title: title || null, p_languages: languages, p_active: form.get("active") === "on",
    });
    if (saveError) return { result: saveError.code === "23505" || saveError.message?.includes("duplicate") ? "duplicate" : "error" };
    const saved = (Array.isArray(data) ? data[0] : data) as { saved_code?: string } | null;
    revalidatePath("/admin/agents");
    revalidatePath("/dashboard", "layout");
    return { result: "saved", code: saved?.saved_code };
  } catch { return { result: "error" }; }
}

export async function assignAgent(_previous: AgentState, form: FormData): Promise<AgentState> {
  try {
    const client = await createClient();
    const { data: { user }, error } = await client.auth.getUser();
    if (error || !(await hasAdminSession(client, user))) return { result: "error" };
    const clientId = String(form.get("user_id") || ""), agentId = String(form.get("agent_id") || "");
    if (!uuid.test(clientId) || (agentId && !uuid.test(agentId))) return { result: "error" };
    const { error: assignError } = await client.rpc("assign_client_agent", { p_user_id: clientId, p_agent_id: agentId || null });
    if (assignError) return { result: "error" };
    revalidatePath("/admin/agents");
    revalidatePath("/dashboard", "layout");
    return { result: "saved" };
  } catch { return { result: "error" }; }
}
