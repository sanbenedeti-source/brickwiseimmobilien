/** "Net" only when the listing states its operating costs; otherwise the yield is before costs. */
export function rentalYieldLabel(locale: Locale, costsStated?: boolean) {
  const copy = targetReturnCopy[locale];
  return costsStated === false ? copy.grossTargetTotalReturn : copy.targetTotalReturn;
}
