-- Run once in Supabase SQL Editor before enabling multilingual property editing.
create table if not exists public.property_translations (
  id bigint generated by default as identity primary key,
  property_slug text not null,
  locale text not null check (locale in ('en', 'de', 'fr', 'es', 'it')),
  title text not null,
  description text not null,
  property_type text,
  highlights jsonb not null default '[]'::jsonb,
  location_description text,
  seo_title text,
  seo_description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (property_slug, locale)
);

create index if not exists property_translations_slug_locale_idx
  on public.property_translations (property_slug, locale);

alter table public.property_translations enable row level security;

drop policy if exists "Property translations are public" on public.property_translations;
create policy "Property translations are public"
on public.property_translations for select
to anon, authenticated
using (true);

create table if not exists public.insight_translations (
  id bigint generated by default as identity primary key,
  insight_slug text not null,
  locale text not null check (locale in ('en', 'de', 'fr', 'es', 'it')),
  title text not null,
  excerpt text not null,
  content jsonb not null default '[]'::jsonb,
  seo_title text,
  seo_description text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique (insight_slug, locale)
);

create index if not exists insight_translations_slug_locale_idx
  on public.insight_translations (insight_slug, locale);

alter table public.insight_translations enable row level security;

drop policy if exists "Insight translations are public" on public.insight_translations;
create policy "Insight translations are public"
on public.insight_translations for select
to anon, authenticated
using (true);

